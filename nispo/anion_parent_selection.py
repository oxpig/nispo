"""Typed, partial comparison of candidate anionic parents under Blue Book P-72.7.

This module compares caller-proved anionic centers. It does not recognize
functional groups, infer centers from formal-charge patterns, or construct
preferred names. In particular, ordinary :mod:`parent_selection` graph facts
are not made applicable to charged structures by this adapter.
"""

from dataclasses import dataclass
from typing import Literal

from .parent_selection import ParentFacts, compare_parents


# P-72.7(d), referring to the order of anionic classes in P-44.1.2.
ANION_CLASS_ORDER = (
    "N", "P", "As", "Sb", "Bi", "Si", "Ge", "Sn", "Pb", "B", "Al",
    "Ga", "In", "Tl", "O", "S", "Se", "Te", "C",
)
_ALLOWED_OPERATIONS = frozenset({"ide", "uide", "ate", "ite", "elide"})


@dataclass(frozen=True, slots=True)
class AnionicCenterFact:
    """One independently identified anionic center, mapped to input atoms.

    Atom IDs are RDKit atom indices in the original, immutable input molecule
    passed to :func:`compare_anionic_parents`; producers should resolve stable
    atom maps back to those indices before constructing facts.

    ``atom_ids`` owns the complete typed center/group; ``charge_atom_ids``
    names the actual negatively charged atom(s) in the input graph. For a
    group-derived center, ``evidence_kind`` and ``proof`` identify the caller's
    exact source-backed matcher and rule. A proof label is provenance, not a
    substitute for the caller's graph validation.
    """

    atom_ids: frozenset[int]
    charge_atom_ids: frozenset[int]
    class_symbol: str
    operation: Literal["ide", "uide", "ate", "ite", "elide"]
    evidence_kind: Literal["skeletal", "group"]
    source_rule: str
    proof: str


@dataclass(frozen=True, slots=True)
class AnionicParentCandidate:
    """Candidate parent and its complete ledger for the compared charge scope.

    Atom IDs use the same original-molecule index convention as
    :class:`AnionicCenterFact`. ``parent_centers`` includes anionic characteristic suffix centers as
    required by P-72.7(a). ``prefix_centers`` records other anionic centers in
    the compared connected structure (P-72.6); these do not count as centers
    of this parent. ``considered_charge_atoms`` must equal the union of charge
    atoms in both ledgers, making omissions and double ownership detectable.

    ``suffix_key`` is a complete, source-derived smaller-is-senior integer key for the
    applicable suffix comparison in P-72.7(e). ``()`` is an explicit proof
    that no applicable anionic suffix remains; ``None`` is unknown. Optional
    ``parent_facts`` are downstream facts supplied by a source-aware producer.
    They must not be generated by applying neutral graph recognition to the
    charged candidate.
    """

    identity: str
    parent_atom_ids: frozenset[int]
    considered_charge_atoms: frozenset[int]
    parent_centers: tuple[AnionicCenterFact, ...]
    prefix_centers: tuple[AnionicCenterFact, ...] = ()
    suffix_key: tuple | None = None
    parent_facts: ParentFacts | None = None
    proof: str = ""


@dataclass(frozen=True, slots=True)
class AnionicParentComparison:
    """Pairwise result: -1 left, +1 right, 0 proved tie, None unknown."""

    preference: int | None
    rule: str
    reason: str
    trace: tuple[tuple[str, object, object], ...] = ()


def _valid_center(mol, center):
    if not isinstance(center, AnionicCenterFact):
        return False, "center is not an AnionicCenterFact"
    if (not center.atom_ids or not center.charge_atom_ids
            or not center.charge_atom_ids <= center.atom_ids):
        return False, "center atom ownership is empty or incomplete"
    if center.class_symbol not in ANION_CLASS_ORDER:
        return False, "anion class is not in the P-44.1.2 class order"
    if center.operation not in _ALLOWED_OPERATIONS:
        return False, "unsupported anionic operation"
    if center.evidence_kind not in {"skeletal", "group"}:
        return False, "unsupported center evidence kind"
    if not center.source_rule or not center.proof:
        return False, "source rule and graph-proof provenance are required"
    count = mol.GetNumAtoms()
    if any(type(i) is not int or i < 0 or i >= count for i in center.atom_ids):
        return False, "center references an atom outside the input graph"
    if any(mol.GetAtomWithIdx(i).GetFormalCharge() >= 0
           for i in center.charge_atom_ids):
        return False, "a claimed charge atom is not negatively charged"
    if any(mol.GetAtomWithIdx(i).GetSymbol() != center.class_symbol
           for i in center.charge_atom_ids):
        return False, "charge atom element does not match the typed anion class"
    return True, ""


def validate_candidate(mol, candidate):
    """Return ``(valid, reason)`` for the atom/charge ledger and candidate."""
    if not isinstance(candidate, AnionicParentCandidate):
        return False, "candidate is not an AnionicParentCandidate"
    if (not candidate.identity or not candidate.parent_atom_ids
            or not candidate.parent_centers or not candidate.considered_charge_atoms):
        return False, "candidate identity and parent atom set are required"
    n_atoms = mol.GetNumAtoms()
    if any(type(i) is not int or i < 0 or i >= n_atoms
           for i in candidate.parent_atom_ids | candidate.considered_charge_atoms):
        return False, "candidate references an atom outside the input graph"
    centers = candidate.parent_centers + candidate.prefix_centers
    if any(not _valid_center(mol, c)[0] for c in centers):
        bad = next(_valid_center(mol, c)[1] for c in centers
                   if not _valid_center(mol, c)[0])
        return False, bad
    for center in candidate.parent_centers:
        if not center.atom_ids <= candidate.parent_atom_ids:
            return False, "a parent center is not wholly owned by the candidate parent"
    for center in candidate.prefix_centers:
        if center.atom_ids & candidate.parent_atom_ids:
            return False, "an anionic prefix center overlaps the candidate parent"
    charge_ids = [atom_id for center in centers for atom_id in center.charge_atom_ids]
    if len(charge_ids) != len(set(charge_ids)):
        return False, "a negatively charged atom is counted more than once"
    if frozenset(charge_ids) != candidate.considered_charge_atoms:
        return False, "charge ledger does not cover the declared comparison scope exactly"
    if candidate.suffix_key is not None and (
            not isinstance(candidate.suffix_key, tuple)
            or any(type(value) is not int for value in candidate.suffix_key)):
        return False, "suffix_key must be a source-derived integer tuple or None"
    return True, ""


def _class_vector(centers):
    counts = {symbol: 0 for symbol in ANION_CLASS_ORDER}
    for center in centers:
        counts[center.class_symbol] += 1
    return tuple(counts[symbol] for symbol in ANION_CLASS_ORDER)


def _metrics(candidate):
    centers = candidate.parent_centers
    return (
        len(centers),
        sum(c.operation in {"ide", "uide"} for c in centers),
        sum(c.operation == "uide" for c in centers),
        _class_vector(centers),
    )


def compare_anionic_parents(mol, left, right):
    """Compare two candidates in P-72.7 order, stopping at unknown evidence.

    The result is suitable for a parent frontier: unknown is never treated as
    a tie. A criterion's values are included in ``trace`` for auditability.
    """
    for candidate in (left, right):
        valid, reason = validate_candidate(mol, candidate)
        if not valid:
            return AnionicParentComparison(None, "validation", reason)
    if left.considered_charge_atoms != right.considered_charge_atoms:
        return AnionicParentComparison(None, "charge-scope",
                                       "Candidates do not cover the same mapped charge scope.")
    a, b = _metrics(left), _metrics(right)
    rules = (
        ("P-72.7(a)", a[0], b[0], True),
        ("P-72.7(b)", a[1], b[1], True),
        ("P-72.7(c)", a[2], b[2], True),
        ("P-72.7(d)", a[3], b[3], True),
    )
    trace = []
    for rule, av, bv, greater_is_better in rules:
        trace.append((rule, av, bv))
        if av != bv:
            preference = (-1 if av > bv else 1) if greater_is_better else (-1 if av < bv else 1)
            return AnionicParentComparison(preference, rule,
                                           "First decisive P-72.7 anion criterion.", tuple(trace))
    if left.suffix_key is None or right.suffix_key is None:
        return AnionicParentComparison(None, "P-72.7(e)/suffix", "Applicable suffix seniority is unproved.", tuple(trace))
    trace.append(("P-72.7(e)/suffix", left.suffix_key, right.suffix_key))
    if left.suffix_key != right.suffix_key:
        return AnionicParentComparison(-1 if left.suffix_key < right.suffix_key else 1,
                                       "P-72.7(e)/suffix", "First decisive suffix-ranking key.", tuple(trace))
    general = compare_parents(left.parent_facts, right.parent_facts)
    trace.append((general.rule, left.parent_facts, right.parent_facts))
    if general.preference is None:
        return AnionicParentComparison(None, general.rule,
                                       "P-72.7(e) general parent comparison is unproved.", tuple(trace))
    return AnionicParentComparison(general.preference, general.rule,
                                   general.reason, tuple(trace))


def anion_parent_frontier(mol, candidates):
    """Return nondominated candidates without sorting unknown comparisons."""
    values = list(candidates)
    edges = [set() for _ in values]
    for i in range(len(values)):
        for j in range(i + 1, len(values)):
            result = compare_anionic_parents(mol, values[i], values[j]).preference
            if result == -1:
                edges[i].add(j)
            elif result == 1:
                edges[j].add(i)
    visiting, visited = set(), set()

    def cyclic(i):
        if i in visiting:
            return True
        if i in visited:
            return False
        visiting.add(i)
        if any(cyclic(j) for j in edges[i]):
            return True
        visiting.remove(i)
        visited.add(i)
        return False

    if any(cyclic(i) for i in range(len(values))):
        return values
    dominated = set().union(*edges) if edges else set()
    return [candidate for i, candidate in enumerate(values) if i not in dominated]

